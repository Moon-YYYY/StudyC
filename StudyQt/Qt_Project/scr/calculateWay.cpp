/**
 * @brief 执行表达式计算（对外主接口）
 * @param expression 用户输入的数学表达式字符串
 * @return double 计算结果
 *
 * 方法说明：
 *   这是外界调用计算器的唯一入口，内部委托给私有方法 parseExpression()。
 *
 * 调用链：
 *   CalculatorWindow::onEqualClicked()
 *     → CalculateWay::calculate("3+5×2")
 *       → CalculateWay::parseExpression("3+5×2", result)
 *         → 返回 true/false
 *       → 返回 result
 *
 * 错误处理：
 *   如果表达式无效（parseExpression 返回 false），calculate 仍返回 0。
 *   调用者（CalculatorWindow）需要负责检查结果的有效性或显示错误提示。
 */
double CalculateWay::calculate(const QString& expression) {
    double result = 0;                          // 初始化结果为 0
    parseExpression(expression, result);        // 调用私有方法解析表达式
    return result;                              // 返回最终计算结果
}

/**
 * @brief 百分号运算
 * @param value 原始数值
 * @return double 除以 100 后的值
 *
 * 数学本质：value ÷ 100
 * 应用场景：用户在计算器上按下 "%" 按钮时触发
 *           例如：输入 50 后按 % → 显示 0.5
 *
 * 精度说明：
 *   使用 double 类型，存在浮点数精度问题。
 *   例如 1 ÷ 100 = 0.01，但 double 实际存储为 0.010000000000000000208...
 *   显示层（CalculatorWindow）负责格式化和四舍五入。
 */
double CalculateWay::handlePercent(double value) {
    return value / 100.0;                       // 直接除以 100.0
}

/**
 * @brief 正负号切换
 * @param value 原始数值
 * @return double 取反后的值
 *
 * 数学本质：value × (-1)
 * 应用场景：用户在计算器上按下 "±" 按钮时触发
 *           例如：5 → -5, -3 → 3
 */
double CalculateWay::handlePlusMinus(double value) {
    return -value;                              // 返回相反数
}

// =============================================================================
// 私有方法：表达式解析核心
// =============================================================================

/**
 * @brief 解析并计算表达式（核心算法实现）
 * @param expression 表达式字符串
 * @param result     输出参数，计算结果
 * @return bool 解析是否成功
 *
 * ========================================
 * 算法详解：两级正则扫描法
 * ========================================
 *
 * 整体策略：
 *   数学运算优先级规则：先乘除，后加减。
 *   我们通过"两轮扫描"来实现这个优先级：
 *   - 第 1 轮：查找并计算所有乘除运算，将结果替换回表达式
 *   - 第 2 轮：在乘除全部处理后，查找并计算所有加减运算
 *
 * 为什么正则替换法可行？
 *   表达式 "3+5×2-4÷2" 在不考虑优先级的情况下从左到右计算会得到：
 *   3+5=8, 8×2=16, 16-4=12, 12÷2=6 → 错误结果 6
 *   但正确结果是 3+10-2=11
 *
 *   通过先处理乘除：
 *   第一轮：找到 "5×2"，计算得 10，替换为 "3+10-4÷2"
 *           找到 "4÷2"，计算得 2，替换为 "3+10-2"
 *   第二轮：找到 "3+10"，计算得 13，替换为 "13-2"
 *           找到 "13-2"，计算得 11，最终结果为 "11"
 *   结果：11 ✓
 *
 * 正则表达式详解：
 *   第一轮使用的正则：(-?[\d.]+)([×÷])(-?[\d.]+)
 *     - (-?[\d.]+) ：捕获组 1，匹配第一个数字
 *       - -?       ：可选负号（匹配以负号开头的数字如 -5）
 *       - [\d.]+   ：一个或多个数字或小数点（匹配整数和小数如 3.14）
 *     - ([×÷])    ：捕获组 2，匹配乘号 × 或除号 ÷
 *     - (-?[\d.]+) ：捕获组 3，匹配第二个数字（同样支持负数）
 *
 *   第二轮使用的正则：(-?[\d.]+)([+\-])(-?[\d.]+)
 *     - 结构同上，但运算符是 + 和 -
 *     - 注意减号在字符组中要转义 [+\-]
 *
 * 循环替换的核心机制：
 *   每次循环：
 *   1. 用正则搜索当前表达式，找到第一个匹配
 *   2. 提取两个操作数和运算符
 *   3. 执行运算
 *   4. 用结果替换原匹配部分
 *   5. 继续搜索，直到没有更多匹配
 *
 * 为什么用 while 循环而不是一次替换所有？
 *   表达式 "10+5×2+3×4"
 *   如果一次替换所有乘除：同时找到 "5×2" 和 "3×4"
 *   替换后变为 "10+10+12"，然后一次处理所有加减 → 没问题
 *   但表达式 "2×3+4×5+6" 也是一样
 *   然而考虑 "-3×2+4"：第一个数字可能是负数，正则匹配 "-3×2"，
 *   替换为 "-6+4"，然后处理加减 → -2  ✓
 *
 *   但逐次替换更安全——确保每次匹配都是针对最新的表达式状态。
 *   还有更复杂的场景需要逐次处理（如嵌套替换需要更新表达式后重新扫描）。
 *
 * 边界情况处理：
 *   1. 空字符串/纯空格：trimmed() 去除首尾空格后 toDouble() 检查
 *   2. 单个数字如 "42"：直接解析为 double 返回
 *   3. 纯负数如 "-5"：toDouble() 也能正确解析
 *   4. 除数为零：返回 0，但理论上应该返回 NaN 或抛出异常
 *   5. 无效表达式如 "3++5"：正则匹配可能失败，最终 toDouble() 可能返回 false
 *
 * 当前实现的局限性：
 *   - 不支括号：例如 "2×(3+4)" 无法正确处理
 *   - 不支连续运算符：如 "5+-3" 或 "3××4"
 *   - 不支持函数：如 sqrt(9)、sin(30)
 *   - 精度问题：double 浮点数在连续运算中会有精度误差
 *     例如 0.1+0.2 在 double 中不等于 0.3
 *
 * 改进方向（如果需要扩展）：
 *   方案一：调车场算法（Shunting-yard）
 *     - 将中缀表达式转为后缀表达式（逆波兰表示法）
 *     - 用栈求值
 *     - 优势：支持任意优先级、括号、函数
 *   方案二：递归下降解析
 *     - 定义语法规则（Expr → Term | Expr + Term）
 *     - 递归调用解析函数
 *     - 优势：代码优雅，易于扩展
 */
bool CalculateWay::parseExpression(const QString& expression, double& result) {
    // ==============================================
    // 第一步：预处理
    // ==============================================

    /**
     * 移除字符串首尾的空格。
     * trimmed() 是 QString 的便捷方法，等价于：
     *   QString s = expr;
     *   s = s.trimmed();  // 移除 \t, \n, \r, 空格等
     *
     * 为什么需要去除空格？
     *   用户输入的表达式可能包含空格，如 "3 + 5 × 2"，
     *   这些空格会影响正则匹配，因为我们的正则是严格匹配
     *   "数字运算符数字" 模式的，中间不能有空格。
     */
    QString expr = expression.trimmed();

    // ==============================================
    // 第二步：检查是否为单个数字
    // ==============================================

    /**
     * 尝试将整个表达式解析为一个 double 数字。
     * QString::toDouble(bool *ok)：
     *   如果字符串可以被解析为有效的浮点数，ok 被设为 true，返回该数字。
     *   如果不能解析（如包含运算符），ok 被设为 false，返回 0.0。
     *
     * 这个步骤的作用：
     *   快速通道——如果用户只输入了一个数字（没有运算符），
     *   直接返回即可，无需进入正则匹配流程。
     *   例如：计算 5 = 5（无需任何运算）
     *
     * 注意：
     *   toDouble() 支持科学计数法，如 "1.5e2" 会被解析为 150.0。
     *   但我们的计算器不需要这个功能，不过也不影响。
     */
    bool ok;
    result = expr.toDouble(&ok);
    if (ok) {
        return true;                            // 单个数字，直接返回成功
    }

    // ==============================================
    // 第三步：处理乘除运算（高优先级）
    // ==============================================

    /**
     * 创建 QRegularExpression 对象。
     *
     * 正则模式详解：(-?[\d.]+)([×÷])(-?[\d.]+)
     *
     * 用图形表示匹配过程：
     *   表达式：           "3 + 5 × 2 - 4 ÷ 2"
     *   第一次匹配：        跳过   ~~~    ^^^^^
     *   第二次匹配（替换后）：            ~~~
     *
     * 捕获组说明：
     *   方法               | 正则片段       | 说明
     *   match.captured(0)  | 整个匹配       | 如 "5×2"
     *   match.captured(1)  | 第一个数字     | 如 "5"
     *   match.captured(2)  | 运算符         | 如 "×"
     *   match.captured(3)  | 第二个数字     | 如 "2"
     *
     * 注意：正则中的反斜杠需要用双反斜杠转义。
     *   \d 在 C++ 字符串中要写成 \\d
     *   \. 在 C++ 字符串中要写成 \\.
     * 这是因为 C++ 中反斜杠本身是转义字符，所以要写两遍。
     */
    QRegularExpression regMulDiv("(-?[\\d.]+)([×÷])(-?[\\d.]+)");
    QRegularExpressionMatch match;              // 匹配结果对象

    /**
     * 循环处理所有乘除运算。
     *
     * while 循环条件：
     *   QRegularExpression::match() 返回一个 QRegularExpressionMatch 对象，
     *   其 hasMatch() 方法返回 true 表示找到了匹配。
     *
     * 每次循环执行的操作：
     *   1. match(expr) 在当前 expression 上执行匹配
     *   2. hasMatch() 检查是否找到匹配
     *   3. 如果找到，提取操作数和运算符
     *   4. 计算结果
     *   5. 用结果字符串替换原表达式中的匹配部分
     *   6. 继续循环，在新表达式上再次搜索
     *
     * 注意：
     *   match() 默认返回第一个匹配，不是全局匹配。
     *   我们正是需要这种"一次一个"的行为——每次替换后重新扫描。
     *   如果使用全局匹配（globalMatch），可能会同时替换多个不相关的部分。
     */
    while ((match = regMulDiv.match(expr)).hasMatch()) {
        /**
         * 提取操作数和运算符。
         *
         * match.captured(int n)：
         *   n = 0：返回整个匹配的字符串
         *   n = 1,2,3：返回对应的捕获组
         *
         * 示例：匹配 "5×2" 时
         *   match.captured(1) → "5"
         *   match.captured(2) → "×"
         *   match.captured(3) → "2"
         *
         * QString::toDouble()：
         *   将字符串转换为 double 类型。
         *   如果字符串不是有效的数字格式，返回 0.0。
         *   在我们的场景中，正则保证了 captured(1) 和 captured(3) 一定是数字字符串，
         *   所以 toDouble() 必然成功。
         */
        double num1 = match.captured(1).toDouble();  // 第一个操作数
        QString op = match.captured(2);               // 运算符（× 或 ÷）
        double num2 = match.captured(3).toDouble();   // 第二个操作数
        double subResult = 0;                         // 临时计算结果

        /**
         * 根据运算符执行对应的数学运算。
         *
         * 乘法和除法：
         *   × 和 ÷ 使用的是 Unicode 字符（U+00D7 和 U+00F7），
         *   不是 ASCII 的 * 和 /。
         *   这是因为计算器界面上的按钮显示的就是 × 和 ÷，
         *   CalculatorWindow 在构建表达式时使用的也是这些字符。
         */
        if (op == "×") {
            subResult = num1 * num2;            // 乘法：num1 × num2
        } else if (op == "÷") {
            /**
             * 除法运算，包含除零检查。
             *
             * 除零处理：
             *   如果除数为 0，直接返回，不进行除法运算。
             *   这里将 result 设为 0 并返回 true。
             *   这是一个简化处理——实际应用中应该返回 Infinity、
             *   NaN 或触发错误提示。
             *
             * 浮点数除法的注意事项：
             *   在 C++ 中，double 的除零行为是：
             *     - 正数/0 → +inf
             *     - 负数/0 → -inf
             *     - 0/0 → NaN
             *   这些值在显示时可能引起问题，所以需要提前检查。
             */
            if (num2 != 0) {
                subResult = num1 / num2;        // 除法：num1 ÷ num2（安全）
            } else {
                result = 0;                     // 除零保护，将结果置为 0
                return true;                    // 仍返回 true 表示解析成功（不报错，但结果是 0）
            }
        }

        /**
         * 将计算结果替换回表达式。
         *
         * QString::replace(const QString &before, const QString &after)：
         *   将字符串中所有匹配 before 的部分替换为 after。
         *   但这里有一个细节——我们只替换了第一个匹配（因为正则 match 是逐次匹配的），
         *   而 replace 可能替换所有相同的子串。
         *   例如 expr = "5×2+5×2"，第一次匹配 "5×2"，
         *   replace 会替换两个 "5×2" 为 "10"，导致 "10+10"。
         *   这实际上不影响最终结果，因为乘除优先级相同，同时替换和逐次替换结果一致。
         *
         * match.captured(0) 是整个匹配的字符串（如 "5×2"），
         * QString::number(subResult) 将 double 转换为字符串（如 "10"），
         * 注意：QString::number 默认使用科学计数法处理超大/超小数字，
         * 但对我们场景中的一般数字，它输出的是标准十进制格式。
         *
         * 替换后 expr 被更新，下一轮循环将在新表达式上继续搜索乘除运算。
         */
        expr.replace(match.captured(0), QString::number(subResult));
    }

    // ==============================================
    // 第四步：处理加减运算（低优先级）
    // ==============================================

    /**
     * 加减运算的正则表达式。
     *
     * 模式：(-?[\d.]+)([+\-])(-?[\d.]+)
     *
     * 与乘除正则结构相同，但运算符改为 + 和 -。
     *
     * 关于减号转义的说明：
     *   在字符组 [+\-] 中，减号需要转义为 \-，
     *   因为减号在字符组中表示范围（如 [a-z]）。
     *   写成 [+\-] 明确表示仅匹配 + 和 - 两个字符，而不是"从 + 到某个字符的范围"。
     *
     * 处理逻辑：
     *   此时表达式中应该只剩下数字和加减运算符了，
     *   因为乘除运算已在上一轮全部处理完毕。
     *   示例：经过第一轮后，"3+10-2" 中只有 + 和 -。
     */
    QRegularExpression regAddSub("(-?[\\d.]+)([+\\-])(-?[\\d.]+)");

    /**
     * 在全部乘除已处理完成的基础上处理加减运算。
     *
     * 算法与乘除处理完全相同，只是运算符变成了 + 和 -。
     *
     * 逐次匹配替换的效果：
     *   表达式 "3+10-2"
     *   第一次循环：匹配 "3+10"，计算得 13，替换为 "13-2"
     *   第二次循环：匹配 "13-2"，计算得 11，替换为 "11"
     *   第三次循环：正则搜索 "11"，没有匹配到 "数字+数字" 模式，退出循环
     *
     * 最终 expr 变为 "11"，即最终结果。
     */
    while ((match = regAddSub.match(expr)).hasMatch()) {
        double num1 = match.captured(1).toDouble();  // 第一个操作数
        QString op = match.captured(2);               // 运算符（+ 或 -）
        double num2 = match.captured(3).toDouble();   // 第二个操作数
        double subResult = 0;                         // 临时计算结果

        if (op == "+") {
            subResult = num1 + num2;            // 加法：num1 + num2
        } else if (op == "-") {
            subResult = num1 - num2;            // 减法：num1 - num2
        }

        // 将计算结果替换回表达式，更新表达式状态
        expr.replace(match.captured(0), QString::number(subResult));
    }

    // ==============================================
    // 第五步：返回最终结果
    // ==============================================

    /**
     * 将最终的表达式字符串转换为 double。
     *
     * 此时 expr 应该已经是纯数字字符串了（如 "11"），
     * 但为了安全起见，仍然用 toDouble() 检查。
     *
     * 如果解析失败（toDouble 返回 false），可能的场景：
     *   - 表达式中有非法字符（如字母）
     *   - 表达式为空字符串
     *   - 表达式格式错误（如 "3+"）
     *
     * 在这些情况下，返回 false 通知调用者计算失败。
     */
    result = expr.toDouble(&ok);                 // 最终转换
    return ok;                                   // 返回解析是否成功
}