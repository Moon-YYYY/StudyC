/******************************************************************************
 * calculateWay.cpp
 * 计算引擎模块 - 实现文件
 *
 * 本文件实现了 CalculateWay 类的所有方法，包含完整的数学表达式解析引擎。
 *
 * 核心算法：两级正则扫描法
 *   传统表达式求值有几种主流方法：
 *     1. 逆波兰表达式（RPN）/ 调车场算法（Shunting-yard）
 *     2. 递归下降解析（Recursive Descent）
 *     3. 双栈算法（操作数栈 + 运算符栈）
 *     4. 正则替换法（本实现采用的方式）
 *
 *   本实现采用"正则替换法"，选择理由：
 *     - 代码量最小，逻辑直观
 *     - 对于不加括号的四则运算足够使用
 *     - 利用 Qt 的 QRegularExpression 提供强大的字符串匹配能力
 *
 * 执行流程：
 *   calculate("3+5×2")  →  parseExpression()  →  乘除优先处理  →  加减处理  →  返回结果
 *
 * Qt 技术要点：
 *   - QRegularExpression：Qt5 引入的正则表达式类，替代了旧的 QRegExp
 *   - QString::toDouble()：字符串转浮点数，支持自动识别正负号和小数点
 *   - QString::replace()：字符串替换，用于将计算结果写回表达式
 ******************************************************************************/

